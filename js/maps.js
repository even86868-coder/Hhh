export function buildEncounter(key, flags = {}) {
  const enc = ENCOUNTERS[key];
  const enemies = enc.enemies.filter((e) => (!e.if || flags[e.if]) && (!e.unless || !flags[e.unless]));
  return {
    ...enc,
    key,
    map: { w: enc.tiles[0].length, h: enc.tiles.length, tiles: enc.tiles, theme: enc.theme },
    enemies,
  };
}
